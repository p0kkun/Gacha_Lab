import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const appRoot = path.resolve(__dirname, '..');
const apiRoot = path.join(appRoot, 'app', 'api');
const outputPath = path.join(appRoot, 'lib', 'lambda-route-manifest.ts');

const isRouteFile = (filePath) => path.basename(filePath) === 'route.ts';

const walk = (dir, files = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, files);
      continue;
    }
    if (entry.isFile() && isRouteFile(fullPath)) {
      files.push(fullPath);
    }
  }
  return files;
};

const toApiPath = (filePath) => {
  const rel = path.relative(apiRoot, path.dirname(filePath));
  if (!rel) {
    return '/api';
  }
  return `/api/${rel.split(path.sep).join('/')}`;
};

const buildRegex = (apiPath) => {
  const paramNames = [];
  const pattern = apiPath
    .split('/')
    .filter(Boolean)
    .map((segment) => {
      const match = segment.match(/^\[(.+)\]$/);
      if (!match) {
        return segment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      }
      const name = match[1];
      paramNames.push(name);
      return '([^/]+)';
    })
    .join('/');
  return {
    regex: `^/${pattern}$`,
    paramNames,
  };
};

const toModulePath = (filePath) => {
  // Lambda package places compiled routes under /var/task/api/...
  const rel = path.relative(apiRoot, filePath).replace(/\.ts$/, '.js');
  const normalized = rel.split(path.sep).join('/');
  return `./api/${normalized}`;
};

const routes = walk(apiRoot)
  .map((filePath) => {
    const apiPath = toApiPath(filePath);
    const { regex, paramNames } = buildRegex(apiPath);
    const modulePath = toModulePath(filePath);
    return {
      path: apiPath,
      modulePath,
      paramNames,
      regex,
    };
  })
  .sort((a, b) => a.path.localeCompare(b.path));

const contents = `/* This file is auto-generated by scripts/generate-lambda-routes.mjs */
export type LambdaRouteEntry = {
  path: string;
  modulePath: string;
  paramNames: string[];
  regex: RegExp;
};

export const lambdaRouteManifest: LambdaRouteEntry[] = [
${routes
  .map(
    (route) =>
      `  { path: '${route.path}', modulePath: '${route.modulePath.replace(/\\/g, '/')}', paramNames: ${JSON.stringify(
        route.paramNames
      )}, regex: new RegExp('${route.regex}') }`
  )
  .join(',\n')}
];
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, contents, 'utf8');
console.log(`Generated lambda route manifest: ${outputPath}`);
