import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const appRoot = path.resolve(__dirname, '..');
const apiRoot = path.join(appRoot, 'app', 'api');
const outputPath = path.join(appRoot, 'lambda', 'route-manifest.ts');

const isRouteFile = (filePath) => path.basename(filePath) === 'route.ts';

const walk = (dir, files = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(fullPath, files);
      continue;
    }
    if (entry.isFile() && isRouteFile(fullPath)) {
      files.push(fullPath);
    }
  }
  return files;
};

const toApiPath = (filePath) => {
  const rel = path.relative(apiRoot, path.dirname(filePath));
  if (!rel) {
    return '/api';
  }
  return `/api/${rel.split(path.sep).join('/')}`;
};

const buildRegex = (apiPath) => {
  const paramNames = [];
  const pattern = apiPath
    .split('/')
    .filter(Boolean)
    .map((segment) => {
      const match = segment.match(/^\[(.+)\]$/);
      if (!match) {
        return segment.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      }
      const name = match[1];
      paramNames.push(name);
      return '([^/]+)';
    })
    .join('/');
  return {
    regex: `^/${pattern}$`,
    paramNames,
  };
};

const toModulePath = (filePath) => {
  const rel = path.relative(apiRoot, filePath);
  const normalized = rel.split(path.sep).join('/');
  // Route files live under app/app/api, and this manifest is in app/lib.
  // So the import path needs ../app/api/...
  return `./app/api/${normalized}`;
};

const routes = walk(apiRoot)
  .map((filePath) => {
    const apiPath = toApiPath(filePath);
    const { regex, paramNames } = buildRegex(apiPath);
    const modulePath = toModulePath(filePath);
    return {
      path: apiPath,
      modulePath,
      paramNames,
      regex,
    };
  })
  .sort((a, b) => {
    // Static routes before dynamic ones so /presigned-url wins over /[id]
    if (a.paramNames.length !== b.paramNames.length) {
      return a.paramNames.length - b.paramNames.length;
    }
    // Longer paths first to avoid accidental prefix captures
    if (a.path.length !== b.path.length) {
      return b.path.length - a.path.length;
    }
    return a.path.localeCompare(b.path);
  });

const importLines = routes
  .map((route, index) => `import * as route${index} from '../${route.modulePath.replace(/^\.\//, '')}';`)
  .join('\n');

const moduleArray = routes.map((_, index) => `  route${index}`).join(',\n');

const contents = `/* This file is auto-generated by scripts/generate-lambda-routes.mjs */
${importLines}

export type LambdaRouteEntry = {
  path: string;
  moduleIndex: number;
  paramNames: string[];
  regex: RegExp;
};

export const lambdaRouteModules = [
${moduleArray}
];

export const lambdaRouteManifest: LambdaRouteEntry[] = [
${routes
  .map(
    (route, index) =>
      `  { path: '${route.path}', moduleIndex: ${index}, paramNames: ${JSON.stringify(
        route.paramNames
      )}, regex: new RegExp('${route.regex}') }`
  )
  .join(',\n')}
];
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, contents, 'utf8');
console.log(`Generated lambda route manifest: ${outputPath}`);
